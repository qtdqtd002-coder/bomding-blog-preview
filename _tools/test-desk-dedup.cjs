#!/usr/bin/env node
/* ============================================================================
   test-desk-dedup.cjs — 재탕 판정 회귀 게이트   (2026-09-20 신설 · LLM 0)

   왜 있나
     09-18 개편으로 추천 제목이 «질의형»으로 짧아지자(«림버스 컴퍼니 하는법») 제목의 대부분을 게임명이 차지하게 됐고,
     desk-dedup 이 내용이 전혀 다른 지난 추천과도 유사도 0.4·공유어 2 를 넘겨 DROP 했다(09-19 실측 2건 · 그날 판이 12건으로 줄어든 원인 하나).
     수리 = 유사도·공유어를 «게임명을 뺀 나머지»로 잰다. 그 수리가 되돌아가지 않도록, 그리고 진짜 재탕은 계속 잡히도록 여기서 고정한다.

   사용: node _tools/test-desk-dedup.cjs     (exit 0 = 통과)
   ========================================================================== */
'use strict';
const D = require('./desk-dedup.cjs');

let n = 0, bad = 0;
const ok = (cond, msg) => { n++; if (cond) console.log('ok   ' + msg); else { bad++; console.log('FAIL ' + msg); } };
const eq = (a, b, msg) => ok(JSON.stringify(a) === JSON.stringify(b), msg + ' → ' + JSON.stringify(a) + (JSON.stringify(a) === JSON.stringify(b) ? '' : ' (기대 ' + JSON.stringify(b) + ')'));

/* 지난 판 항목 — 적재와 같은 함수로 만든다 */
const past = (game, title, extra) => D.pastItem(Object.assign({ game, title }, extra || {}), '2026-09-13', (extra && extra.sec) || 'core');
const v = (cand, list) => D.judge(cand, list).verdict;

console.log('[1] 게임명 제거');
eq(D.stripGame('림버스 컴퍼니 하는법', '림버스컴퍼니').trim(), '하는법', '붙여 쓴 게임명도 지운다');
eq(D.stripGame('카오스 제로 나이트메어 장비 세팅', '카오스 제로 나이트메어').trim(), '장비 세팅', '띄어 쓴 게임명 전체를 지운다');
eq(D.stripGame('제목에 게임명이 없다', '메이플스토리'), '제목에 게임명이 없다', '없으면 제목 그대로');
eq(D.stripGame('무엇이든', ''), '무엇이든', '게임명이 비면 제목 그대로');

console.log('\n[2] ★09-19 오탐 재발 방지 — 게임명만 같고 내용이 다르면 DROP 아니다');
ok(v({ game: '림버스컴퍼니', title: '림버스 컴퍼니 하는법' },
     [past('림버스컴퍼니', '림버스컴퍼니 시즌7 정가 우선순위')]) !== 'DROP', '«하는법» vs «시즌7 정가 우선순위»');
ok(v({ game: '카오스 제로 나이트메어', title: '카오스 제로 나이트메어 장비 세팅 신의 망치 델랑 상점' },
     [past('카오스 제로 나이트메어', '카오스 제로 나이트메어 티어표 최신 순위는 어떻게 바뀌었나')]) !== 'DROP', '«장비 세팅» vs «티어표 순위»');
ok(v({ game: '애니모', title: '애니모 하는법 처음 시작하는 사람을 위한 기초 정리' },
     [past('애니모', '애니모 포지션 5종 뭐부터 키워야 하나')]) !== 'DROP', '«하는법» vs «포지션 5종»');

console.log('\n[3] 진짜 재탕은 계속 DROP');
eq(v({ game: '마비노기', title: '마비노기 탈라 가흐 던전 입장 조건과 공략' },
     [past('마비노기', '마비노기 신규 던전 탈라 가흐 — 입장 조건·통행증·클리어 보상 정리')]), 'DROP', '같은 던전·같은 각도');
eq(v({ game: '하늘의 궤적 the2nd', title: '하늘의 궤적 the2nd 한국어판 정식 출시, 첫인상과 시스템 정리' },
     [past('하늘의 궤적 the 2nd', '하늘의 궤적 the 2nd 한국어판 정식 출시, 첫인상과 시스템 정리')]), 'DROP', '제목이 사실상 같다');
eq(v({ game: '롤토체스', title: '롤토체스 18.2b 패치 변경점 정리' },
     [past('롤토체스', '롤토체스 18.2b 카밀 르블랑 티모 변경 정리')]), 'DROP', '같은 게임 + 같은 패치 앵커(18.2b)');

console.log('\n[3-2] ★질의형 제목 — 앞머리 질의가 같으면 재탕(게임명·흔한 말을 빼면 bigram 으로는 안 잡힌다)');
eq(v({ game: '리그 오브 레전드', title: '리그 오브 레전드 게임 방법, 처음 시작할 때 알아야 할 것' },
     [past('리그 오브 레전드', '리그오브레전드 게임방법, 넥서스 파괴까지 공식 하우투플레이', { sec: 'guide' })]), 'DROP', '띄어쓰기만 다른 같은 질의');
eq(v({ game: '팰월드', title: '팰월드 공략 순서 레벨별 정리' },
     [past('팰월드', '팰월드 공략, 초반에 뭘 먼저 하나', { sec: 'core' })]), 'DROP', '한쪽이 다른 쪽 질의를 품는다');
eq(v({ game: '애니모', title: '애니모 하는법 처음 시작하는 사람을 위한 기초 정리' },
     [past('롤토체스', '롤토체스 하는법 처음 시작하는 사람을 위한 기초 정리', { sec: 'pinned' })]), 'CHECK',
   '같은 문틀이라도 게임이 다르면 DROP 아니다(사람이 보라는 CHECK 까지만)');

console.log('\n[4] 게임이 다르면 문형이 같아도 다른 글');
ok(v({ game: '제우스: 오만의 신', title: '제우스 오만의 신 쿠폰 입력하는 법, 어디서 넣나' },
     [past('애니모', '애니모 쿠폰 코드 입력하는 법, 어디서 넣나')]) !== 'DROP', '쿠폰 입력법은 게임마다 따로 쓴다');

console.log('\n[5] 육아는 제품군이 같으면 그 자체로 재탕(규칙 유지)');
eq(v({ game: '아기 가습기', title: '아기 가습기 종류별 차이 정리' },
     [past('아기 가습기', '아기 가습기 초음파식 가열식 복합식, 우리 아이 방엔 뭐가 맞을까', { sec: 'parenting' })]), 'DROP', '같은 제품 카테고리');

console.log('\n[6] 지난 판과 무관하면 OK');
eq(v({ game: '팰월드', title: '팰월드 공략 순서 레벨별 정리' }, [past('메이플스토리', '메이플스토리 아우룸 레기스 공략')]), 'OK', '겹치는 게 없다');

console.log('\n' + (bad ? 'FAIL ' + bad + '/' + n : 'ALL PASS ' + n));
process.exit(bad ? 1 : 0);
